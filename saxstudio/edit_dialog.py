"""Floating time-edit window: video preview, zoomable waveform and cut tools.

The window only lays out widgets; MainWindow wires them to its editing logic
(the same trim / split / delete / undo code the main window always used).
"""
from __future__ import annotations

from . import theme
from .qt import QtCore, QtWidgets as W, QtMultimediaWidgets
from .widgets import MirrorTimeline


def _spin(lo, hi, value, decimals, suffix):
    s = W.QDoubleSpinBox()
    s.setRange(lo, hi)
    s.setDecimals(decimals)
    s.setValue(value)
    s.setSuffix(suffix)
    s.setKeyboardTracking(False)
    return s


class EditDialog(W.QDialog):
    def __init__(self, master_timeline, parent=None):
        super().__init__(parent)
        self.setWindowTitle("時間剪輯")
        self.setModal(True)
        self.resize(1120, 780)
        self.setMinimumSize(900, 640)
        root = W.QVBoxLayout(self)
        root.setContentsMargins(16, 14, 16, 12)
        root.setSpacing(12)

        head = W.QHBoxLayout()
        title = W.QLabel("✂  時間剪輯")
        theme.apply(title, "font-size: 16px; font-weight: 700;")
        head.addWidget(title)
        note = W.QLabel("影片與伴奏同步剪輯 · 剪輯不會修改原始檔")
        note.setObjectName("muted")
        head.addWidget(note)
        head.addStretch()
        root.addLayout(head)

        top = W.QHBoxLayout()
        top.setSpacing(14)
        left = W.QVBoxLayout()
        left.setSpacing(8)
        self.video_stack = W.QStackedWidget()
        self.video_stack.setMinimumSize(480, 270)
        self.video_widget = QtMultimediaWidgets.QVideoWidget()
        self.video_still = W.QLabel("影片預覽")
        self.video_still.setAlignment(QtCore.Qt.AlignCenter)
        self.video_still.setObjectName("muted")
        theme.apply(self.video_still, "background: #0b121c; color: #8498ae; border: 1px solid #304359; border-radius: 8px;")
        self.video_stack.addWidget(self.video_widget)
        self.video_stack.addWidget(self.video_still)
        left.addWidget(self.video_stack, 1)
        transport = W.QHBoxLayout()
        self.play_button = W.QPushButton("▶ 播放")
        self.play_button.setObjectName("primary")
        transport.addWidget(self.play_button)
        self.prev_button = W.QPushButton("◀ 1 格")
        self.prev_button.setToolTip("往前一格（1/30 秒）")
        self.next_button = W.QPushButton("1 格 ▶")
        self.next_button.setToolTip("往後一格（1/30 秒）")
        transport.addWidget(self.prev_button)
        transport.addWidget(self.next_button)
        transport.addStretch()
        self.time_label = W.QLabel("00:00.000 / 00:00.000")
        transport.addWidget(self.time_label)
        left.addLayout(transport)
        top.addLayout(left, 5)

        right = W.QVBoxLayout()
        right.setSpacing(10)
        keep = W.QFrame()
        keep.setObjectName("card")
        grid = W.QVBoxLayout(keep)
        grid.setContentsMargins(12, 10, 12, 10)
        grid.setSpacing(8)
        label = W.QLabel("保留範圍")
        theme.apply(label, "font-weight: 700;")
        grid.addWidget(label)
        marks = W.QHBoxLayout()
        self.start_button = W.QPushButton("起點 ←")
        self.start_button.setToolTip("把起點設為目前游標位置")
        self.mark_start = _spin(0, 86400, 0, 3, " s")
        self.end_button = W.QPushButton("終點 ←")
        self.end_button.setToolTip("把終點設為目前游標位置")
        self.mark_end = _spin(0, 86400, 0, 3, " s")
        for widget in (self.start_button, self.mark_start, self.end_button, self.mark_end):
            marks.addWidget(widget)
        grid.addLayout(marks)
        buttons = W.QHBoxLayout()
        self.trim_button = W.QPushButton("保留起訖範圍")
        self.split_button = W.QPushButton("分割 Ctrl+B")
        self.delete_button = W.QPushButton("刪除片段")
        self.delete_button.setObjectName("danger")
        for widget in (self.trim_button, self.split_button, self.delete_button):
            buttons.addWidget(widget)
        grid.addLayout(buttons)
        auto = W.QHBoxLayout()
        self.autotrim_button = W.QPushButton("依伴奏自動裁剪")
        self.autotrim_button.setObjectName("editButton")
        auto.addWidget(self.autotrim_button)
        auto.addWidget(W.QLabel("伴奏前"))
        self.pre_roll = _spin(0, 30, 3.0, 1, " s")
        auto.addWidget(self.pre_roll)
        auto.addWidget(W.QLabel("伴奏後"))
        self.post_roll = _spin(0, 30, 2.0, 1, " s")
        auto.addWidget(self.post_roll)
        auto.addStretch()
        grid.addLayout(auto)
        right.addWidget(keep)
        clips_head = W.QHBoxLayout()
        label = W.QLabel("保留片段")
        theme.apply(label, "font-weight: 700;")
        clips_head.addWidget(label)
        clips_head.addStretch()
        hint = W.QLabel("點選片段可在波形上標示")
        hint.setObjectName("muted")
        clips_head.addWidget(hint)
        right.addLayout(clips_head)
        self.clip_list = W.QListWidget()
        right.addWidget(self.clip_list, 1)
        top.addLayout(right, 4)
        root.addLayout(top, 1)

        wave_head = W.QHBoxLayout()
        legend = W.QLabel("■ 第一軌　　■ 伴奏")
        legend.setObjectName("muted")
        wave_head.addWidget(legend)
        wave_head.addStretch()
        wave_head.addWidget(W.QLabel("縮放"))
        self.zoom = W.QSlider(QtCore.Qt.Horizontal)
        self.zoom.setRange(1, 8)
        self.zoom.setValue(1)
        self.zoom.setFixedWidth(140)
        self.zoom.setAccessibleName("波形縮放")
        wave_head.addWidget(self.zoom)
        self.zoom_label = W.QLabel("1×")
        wave_head.addWidget(self.zoom_label)
        root.addLayout(wave_head)
        self.timeline = MirrorTimeline(master_timeline)
        self.timeline_scroll = W.QScrollArea()
        self.timeline_scroll.setWidgetResizable(True)
        self.timeline_scroll.setWidget(self.timeline)
        self.timeline_scroll.setMinimumHeight(210)
        self.timeline_scroll.setVerticalScrollBarPolicy(QtCore.Qt.ScrollBarAlwaysOff)
        root.addWidget(self.timeline_scroll)
        self.zoom.valueChanged.connect(self.set_zoom)

        foot = W.QHBoxLayout()
        self.undo_button = W.QPushButton("復原剪輯 Ctrl+Z")
        self.reset_button = W.QPushButton("重設剪輯")
        foot.addWidget(self.undo_button)
        foot.addWidget(self.reset_button)
        self.duration_label = W.QLabel("輸出長度 00:00.000")
        foot.addWidget(self.duration_label)
        foot.addStretch()
        self.cancel_button = W.QPushButton("取消")
        self.cancel_button.setToolTip("放棄這次在視窗裡做的剪輯")
        self.cancel_button.clicked.connect(self.reject)
        self.done_button = W.QPushButton("完成")
        self.done_button.setObjectName("primary")
        self.done_button.setDefault(True)
        self.done_button.clicked.connect(self.accept)
        foot.addWidget(self.cancel_button)
        foot.addWidget(self.done_button)
        root.addLayout(foot)

    def set_zoom(self, value):
        self.zoom_label.setText(f"{value}×")
        width = max(1, self.timeline_scroll.viewport().width())
        self.timeline.setMinimumWidth(int(width * value) if value > 1 else 0)

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self.set_zoom(self.zoom.value())

    def show_video(self, available, message=""):
        if available:
            self.video_stack.setCurrentWidget(self.video_widget)
        else:
            self.video_still.setText(message or "影片預覽")
            self.video_stack.setCurrentWidget(self.video_still)
